-- =====================================================
-- F1 STRATEGY & TELEMETRY ENGINE
-- Database Schema - Version 1
-- =====================================================

-- 1. CIRCUITS
CREATE TABLE IF NOT EXISTS circuits (
    circuit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    circuit_name VARCHAR(150) NOT NULL,
    location VARCHAR(100),
    country VARCHAR(100),
    length_km NUMERIC(7,3)
);

-- 2. SESSIONS
CREATE TABLE IF NOT EXISTS sessions (
    session_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    circuit_id BIGINT NOT NULL,
    season_year INTEGER NOT NULL,
    grand_prix VARCHAR(150) NOT NULL,
    session_type VARCHAR(30) NOT NULL,
    session_date DATE,

    CONSTRAINT fk_session_circuit
        FOREIGN KEY (circuit_id)
        REFERENCES circuits(circuit_id),

    CONSTRAINT uq_session
        UNIQUE (season_year, grand_prix, session_type)
);

-- 3. DRIVERS
CREATE TABLE IF NOT EXISTS drivers (
    driver_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    driver_code VARCHAR(3) NOT NULL,
    full_name VARCHAR(150) NOT NULL,
    nationality VARCHAR(80)
);

-- 4. STINTS
CREATE TABLE IF NOT EXISTS stints (
    stint_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL,
    driver_id BIGINT NOT NULL,
    stint_number INTEGER NOT NULL,
    compound VARCHAR(30),
    start_lap INTEGER,
    end_lap INTEGER,
    tyre_life_start NUMERIC(6,2),

    CONSTRAINT fk_stint_session
        FOREIGN KEY (session_id)
        REFERENCES sessions(session_id),

    CONSTRAINT fk_stint_driver
        FOREIGN KEY (driver_id)
        REFERENCES drivers(driver_id),

    CONSTRAINT uq_stint
        UNIQUE (session_id, driver_id, stint_number),

    CONSTRAINT uq_stint_reference
        UNIQUE (stint_id, session_id, driver_id)
);

-- 5. LAPS
CREATE TABLE IF NOT EXISTS laps (
    lap_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL,
    driver_id BIGINT NOT NULL,
    stint_id BIGINT,
    lap_number INTEGER NOT NULL,
    lap_time_ms NUMERIC(10,3),
    sector_1_ms NUMERIC(10,3),
    sector_2_ms NUMERIC(10,3),
    sector_3_ms NUMERIC(10,3),
    speed_trap_kph NUMERIC(6,2),
    position INTEGER,
    is_personal_best BOOLEAN DEFAULT FALSE,

    CONSTRAINT fk_lap_session
        FOREIGN KEY (session_id)
        REFERENCES sessions(session_id),

    CONSTRAINT fk_lap_driver
        FOREIGN KEY (driver_id)
        REFERENCES drivers(driver_id),

    CONSTRAINT fk_lap_stint
        FOREIGN KEY (stint_id, session_id, driver_id)
        REFERENCES stints(stint_id, session_id, driver_id),

    CONSTRAINT uq_lap
        UNIQUE (session_id, driver_id, lap_number)
);

-- 6. TELEMETRY
CREATE TABLE IF NOT EXISTS telemetry (
    telemetry_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lap_id BIGINT NOT NULL,
    sample_index INTEGER NOT NULL,
    distance_m NUMERIC(10,3),
    speed_kph NUMERIC(7,2),
    throttle_pct NUMERIC(5,2),
    brake BOOLEAN,
    gear SMALLINT,
    rpm INTEGER,
    drs SMALLINT,

    CONSTRAINT fk_telemetry_lap
        FOREIGN KEY (lap_id)
        REFERENCES laps(lap_id),

    CONSTRAINT uq_telemetry_sample
        UNIQUE (lap_id, sample_index)
);

-- =====================================================
-- INDEXES FOR FASTER DATA RETRIEVAL
-- =====================================================

CREATE INDEX IF NOT EXISTS idx_sessions_circuit
    ON sessions(circuit_id);

CREATE INDEX IF NOT EXISTS idx_stints_driver
    ON stints(driver_id);

CREATE INDEX IF NOT EXISTS idx_laps_session
    ON laps(session_id);

CREATE INDEX IF NOT EXISTS idx_laps_driver
    ON laps(driver_id);

CREATE INDEX IF NOT EXISTS idx_telemetry_lap
    ON telemetry(lap_id);
